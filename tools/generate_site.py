#!/usr/bin/env python3
"""Generate every page of the site. Run from the project root:  python3 tools/generate_site.py"""
import os, sys, json, glob
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_common as g, gen_routes, gen_static

for f in glob.glob(os.path.join(g.ROOT, "*.html")):
    os.remove(f)          # only generated pages live in the root
g.build_routes()
gen_routes.build_all()
gen_static.build_all()

places = [[p["name"], p["label"], p["slug"], p["code"], p["country"]] for p in g.PLACES]
routes = {k: [f"{a['slug']}-to-{b['slug']}" for a, b, _ in v] for k, v in g.RT.items()}
with open(os.path.join(g.ROOT, "assets/js/places-data.js"), "w", encoding="utf-8") as f:
    f.write("/* Generated by tools/generate_site.py. Do not edit by hand. */\n")
    f.write("window.TRAVEL_PLACES=" + json.dumps(places, ensure_ascii=False, separators=(",", ":")) + ";\n")
    f.write("window.TRAVEL_ROUTES=" + json.dumps(routes, separators=(",", ":")) + ";\n")
# every UK and US place name for the search box (suggestions only; no pages are made for these)
import search_cities
data = {"UK": {}, "US": {}}
def add(ctry, reg, name):
    data[ctry].setdefault(reg, set()).add(name)
dd = os.path.join(os.path.dirname(os.path.abspath(__file__)), "data")
for reg, names in json.load(open(os.path.join(dd, "gb_places.json"), encoding="utf-8")).items():
    for n in names: add("UK", reg, n)
for reg, names in json.load(open(os.path.join(dd, "us_places.json"), encoding="utf-8")).items():
    for n in names: add("US", reg, n)
for ctry, reg, name in search_cities.parse():
    add("UK" if ctry == "UK" else "US", reg, name)
out = {c: {r: sorted(v) for r, v in sorted(regs.items())} for c, regs in data.items()}
total = sum(len(v) for regs in out.values() for v in regs.values())
with open(os.path.join(g.ROOT, "assets/js/search-cities.js"), "w", encoding="utf-8") as f:
    f.write("/* Generated by tools/generate_site.py. Search suggestions only. Names: GeoNames (CC BY 4.0) and US Cities Database (MIT). */\n")
    f.write("window.TRAVEL_SEARCH=" + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n")
print("search suggestions:", total, "place names")
open(os.path.join(g.ROOT, ".nojekyll"), "w").close()
print("pages:", len(g.PAGES), "| places:", len(g.PLACES), "| routes:", {k: len(v) for k, v in g.RT.items()})
